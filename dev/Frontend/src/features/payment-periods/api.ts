import "server-only";

import type * as z from "zod";
import type { PaymentPeriod } from "@/features/catalogs/types";
import { apiCreate, apiGet, apiGetOptional, apiSend, type Paged } from "@/lib/api";
import type { paymentPeriodRequestSchema } from "./schema";
import type { PaymentPeriodRequest, PaymentPeriodRequestListItem } from "./types";

export function listPaymentPeriodRequests(page: number, pageSize: number) {
  return apiGet<Paged<PaymentPeriodRequestListItem>>("/payment-period-requests", { page, pageSize });
}

export function getPaymentPeriodRequest(id: number) {
  return apiGetOptional<PaymentPeriodRequest>(`/payment-period-requests/${id}`);
}

export function createPaymentPeriodRequest(input: z.output<typeof paymentPeriodRequestSchema>) {
  return apiCreate("/payment-period-requests", input);
}

export function updatePaymentPeriodRequest(id: number, input: z.output<typeof paymentPeriodRequestSchema>) {
  return apiSend("PUT", `/payment-period-requests/${id}`, input);
}

export function deletePaymentPeriodRequest(id: number) {
  return apiSend("DELETE", `/payment-period-requests/${id}`);
}

/** Payment dates generated by the scheduling service for a request. */
export function listPaymentPeriods(requestId: number, page: number, pageSize: number) {
  return apiGet<Paged<PaymentPeriod>>("/payment-periods", { requestId, page, pageSize });
}
